CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL
);
CREATE TABLE suppliers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL,
 owner_user_id BIGINT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_supplier_owner ON suppliers(owner_user_id);
CREATE TABLE inventory_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_id BIGINT NOT NULL,
 name VARCHAR(255) NOT NULL,
 quantity INTEGER NOT NULL,
 reorder_level INTEGER NOT NULL,
 unit_price DECIMAL(15,2) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT ck_inventory_quantity CHECK (quantity >= 0)
);
CREATE INDEX idx_inventory_supplier ON inventory_items(supplier_id);
CREATE TABLE purchase_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL,
 supplier_id BIGINT NOT NULL,
 delivery_address VARCHAR(255) NOT NULL,
 status VARCHAR(24) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 total DECIMAL(15,2) NOT NULL
);
CREATE INDEX idx_order_customer ON purchase_orders(customer_id);
CREATE INDEX idx_order_supplier ON purchase_orders(supplier_id);
CREATE TABLE order_lines (
 order_id BIGINT NOT NULL,
 item_id BIGINT NOT NULL,
 quantity INTEGER NOT NULL,
 unit_price DECIMAL(15,2) NOT NULL,
 CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES purchase_orders(id)
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 order_id BIGINT NOT NULL,
 kind VARCHAR(255) NOT NULL,
 message VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_notification_order_kind UNIQUE (order_id,kind)
);
CREATE INDEX idx_notification_user_created ON notifications(user_id,created_at);
